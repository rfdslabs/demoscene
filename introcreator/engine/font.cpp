  static int index_of(char c) {
    if (c >= 'a' && c <= 'z') c = char(c - 'a' + 'A'); // lowercase -> uppercase
    int i = (unsigned char)c - 32;
    if (i < 0 || i >= 59) return 0;                     // unknown -> space
    return i;
  }

  const unsigned char* glyph(char c) { return TABLE[index_of(c)]; }

  bool glyph_pixel(char c, int gx, int gy) {
    if ((unsigned)gx >= 8 || (unsigned)gy >= 8) return false;
    return (TABLE[index_of(c)][gy] & (0x80 >> gx)) != 0;
  }

  int text_width(const char* s) {
    int n = 0; while (s && s[n]) n++;
    return n * GW;
  }

  void draw(Surface& surf, int x, int y, const char* str, unsigned char color) {
    for (int ci = 0; str && str[ci]; ++ci) {
      const unsigned char* g = glyph(str[ci]);
      int ox = x + ci * GW;
      for (int gy = 0; gy < GH; ++gy)
        for (int gx = 0; gx < GW; ++gx)
          if (g[gy] & (0x80 >> gx)) surf.put(ox + gx, y + gy, color);
    }
  }

